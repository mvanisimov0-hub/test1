// Климатические параметры населённых пунктов регионов, где работает компания.
// Значения — исходные данные для расчёта нагрузок, поэтому каждое можно поправить в расчёте.
//
// Источники:
// - снеговой и ветровой районы — карты 1 и 2 приложения Е СП 20.13330.2016 (с Изменениями № 1–6);
//   районы сняты с карт мелкого масштаба, для пунктов у границы районов принят больший район
//   и выставлен признак check — такие значения нужно подтвердить по месту;
// - Sg — таблица К.1 СП 20.13330.2016 для городов, которые в ней есть (п. 10.2);
// - отопительный период — СП 131.13330.2025; если пункта в таблице нет, взята ближайшая станция (heatRef);
// - глубина промерзания суглинков и глин — 0,23·√Mt по среднемесячным температурам той же станции.

export interface Settlement {
  id: string;
  name: string;
  region: string;
  /** снеговой район */
  snow: number;
  /** Sg по табл. К.1, кПа; null — принимается по району */
  sg: number | null;
  /** ветровой район */
  wind: string;
  /** отопительный период (≤ 8 °C): средняя температура, °C, и длительность, сут */
  tHeat: number;
  zHeat: number;
  /** нормативная глубина промерзания суглинков и глин, м */
  frost: number;
  /** станция-аналог для климатических данных, если пункта нет в СП 131 */
  heatRef: string | null;
  /** пункт у границы районов: значение принято с запасом и требует проверки */
  check: boolean;
}

