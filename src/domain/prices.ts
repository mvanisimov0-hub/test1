/** Справочник пользователя, дополненный новыми позициями по умолчанию */
export function mergePrices(saved: PriceItem[] | undefined): PriceItem[] {
  if (!saved?.length) return DEFAULT_PRICES.map((p) => ({ ...p }));
  const byId = new Map(saved.map((p) => [p.id, p]));
  return DEFAULT_PRICES.map((d) => {
    const s = byId.get(d.id);
    return s ? { ...d, mat: s.mat, work: s.work } : { ...d };
  });
}

export type PriceMap = Record<string, PriceItem>;

export function priceMap(prices: PriceItem[]): PriceMap {
  const m: PriceMap = {};
  for (const d of DEFAULT_PRICES) m[d.id] = d;
  for (const p of prices) m[p.id] = p;
  return m;
}
